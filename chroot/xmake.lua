includes("bash")
includes("coreutils")
includes("diffutils")
includes("file")
includes("findutils")
includes("gawk")
includes("grep")
includes("gzip")
includes("make")
includes("m4")
includes("patch")
includes("sed")
includes("tar")
includes("xz")

target("chroot")
    set_default(false)
    set_kind("phony")
    add_deps("bash-cross-native-build")
    add_deps("coreutils-cross-native-build")
    add_deps("diffutils-cross-native-build")
    add_deps("file-cross-native-build")
    add_deps("findutils-cross-native-build")
    add_deps("gawk-cross-native-build")
    add_deps("grep-cross-native-build")
    add_deps("gzip-cross-native-build")
    add_deps("make-cross-native-build")
    add_deps("m4-cross-native-build")
    add_deps("patch-cross-native-build")
    add_deps("sed-cross-native-build")
    add_deps("tar-cross-native-build")
    add_deps("xz-cross-native-build")
    on_build(function (target)
        import("core.project.project")
        local toolchain_env = project.target("toolchain-env")
        os.cd(toolchain_env:get("toolchain.cross_native.sysroot"))
        if not os.exists("bin") then
            os.exec("ln -fs usr/bin bin")
        end
        os.cd("usr/bin")
        if not os.exists("sh") then
            os.exec("ln -fs bash sh")
        end
    end)